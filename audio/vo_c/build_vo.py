# Version C VO assembly: picks -> trimmed, processed line wavs + cues + src/voC.ts (word times from ElevenLabs character alignment).
# Narrator chain = Version B post chain (HPF75, +2 dB @180, -1.5 dB @350, 3:1 comp). Dialogue adds a light video-call colour (HPF 160 / LPF 7.5 k / +2 dB @2.5 k) so it reads as "on the call" yet stays clear.
import json,subprocess,numpy as np,re
from span import span
PICKS=[('n01','n01_s51',0.25),('n02','n02_s23',0.30),('n03','n03_s51',0.28),
('d1p','d1p_s11',0.32),('d1r','d1r_s11',0.50),('d1p2','d1p2_s11',0.28),
('n05','n05_s23',1.25),   # 1.0 s freeze/silence after "At nine." then black, line 0.25 s in
('n06','n06_s37',0.40),('n07','n07_s37',0.30),('n08','n08_s37',0.30),('n09','n09_s37',0.30),
('n10','n10_s37',0.30),('n11','n11_s23',0.30),
('d2p','d2p_s37',0.38),('d2r','d2r_s23',0.22),('d2p2','d2p2_s11',0.38),
('n13','_v1/n13_s23',0.40)]
END_HOLD=0.9
NAR="highpass=f=75:poles=2,lowshelf=f=180:g=2:w=0.7,equalizer=f=350:t=q:w=1.2:g=-1.5,acompressor=threshold=-22dB:ratio=3:attack=12:release=80:makeup=2"
DIA="highpass=f=160:poles=2,lowpass=f=7500,equalizer=f=2500:t=q:w=1.0:g=2,acompressor=threshold=-22dB:ratio=3:attack=10:release=80:makeup=2"
GOLD={'nine.','AI','limit','reached.','Re-upload.','Expired.','you.','alone.','associates.','reads','digs','redlines','drafts','once,','sleep.','done,','yes.','Eleven','inbox.','fast.','review.','decide.','fare','rules','Mike','Garry','Fiona','DEL–AUH?','DEL–AUH.','board.'}
SHOW={'Delhi–Abu':'DEL–AUH','Eleven forty-one P.M.':'11:41 PM'}
out={}; t=0.0; prev_end=0.0
for n,src,gap in PICKS:
    f=f'takes/{src}.mp3'; a,b,dur=span(f)
    a0=max(0,a-0.02); b0=min(dur,b+0.12)
    who='N' if n[0]=='n' else ('P' if n.endswith('p') or n.endswith('p2') else 'R')
    subprocess.run(['ffmpeg','-y','-v','error','-ss',f'{a0:.3f}','-to',f'{b0:.3f}','-i',f,'-af',(NAR if who=='N' else DIA)+f',afade=t=in:d=0.005,afade=t=out:st={b0-a0-0.04:.3f}:d=0.04','-ar','48000','-ac','1','-c:a','pcm_s24le',f'{n}.wav'],check=True)
    at=round(prev_end+gap - (a-a0),3)   # speech onset lands exactly gap after previous speech end
    if n=='n01': at=round(gap-(a-a0),3)
    j=json.load(open(f'takes/{src}.json'))['alignment']; ch=j['characters']; st=j['character_start_times_seconds']; en=j['character_end_times_seconds']
    words=[]; cur=''; ws=None; we=None
    for c,s,e in zip(ch,st,en):
        if c.isspace():
            if cur: words.append([cur,ws,we]); cur=''
        else:
            if not cur: ws=s
            cur+=c; we=e
    if cur: words.append([cur,ws,we])
    # drop SSML remnants, map spoken forms -> on-screen tokens
    words=[w for w in words if not re.match(r'^(<break|time=|/>)',w[0])]
    txt=' '.join(w[0] for w in words)
    if n=='n01':  # "Eleven forty-one P.M." -> "11:41 PM"
        words=[['11:41',words[0][1],words[1][2]],['PM.',words[2][1],words[2][2]]]+words[3:]
    words=[[w[0].replace('Delhi–Abu','DEL–AUH').replace('...','…'),w[1],w[2]] for w in words if w[0] not in ('Dhabi?','Dhabi.')]
    words=[[('DEL–AUH?' if w[0]=='DEL–AUH' and n=='d1p' else 'DEL–AUH.' if w[0]=='DEL–AUH' else w[0]),w[1],w[2]] for w in words]
    if n=='d2r':  # "Dhabi." end time -> extend DEL–AUH.
        pass
    # clamp to trimmed audio and offset to timeline
    W=[[w[0],round(at+max(0,w[1]-a0),3),round(at+max(0.05,w[2]-a0),3)] for w in words]
    # Delhi–Abu Dhabi spans two words: extend DEL–AUH to cover the dropped "Dhabi"
    if 'Dhabi' in txt:
        orig=[w for w in json.loads(json.dumps(words))]
    out[n]=dict(who=who,src=src,at=at,dur=round(b0-a0,3),start=round(at+(a-a0),3),end=round(at+(b-a0),3),words=W)
    prev_end=at+(b-a0)
# fix DEL–AUH end times: use next word start - 0.05
for n,v in out.items():
    ws=v['words']
    for i,w in enumerate(ws):
        if w[0].startswith('DEL–AUH') and i+1<len(ws): w[2]=round(ws[i+1][1]-0.05,3)
        elif w[0].startswith('DEL–AUH'): w[2]=v['end']
TOTAL=round(prev_end+END_HOLD,3)
json.dump(dict(lines=out,total=TOTAL),open('cues.json','w'),indent=1)
for n,v in out.items(): print(f"{n:5s} {v['who']} {v['start']:6.2f}-{v['end']:6.2f}  {' '.join(w[0] for w in v['words'])}")
print('TOTAL',TOTAL, 'frames',round(TOTAL*30))
open('../../src/voC.ts','w').write('// GENERATED by audio/vo_c/build_vo.py (ElevenLabs alignment word times, seconds on the Version C timeline).\nexport type W = [string, number, number];\nexport type Line = {who: "N" | "P" | "R"; at: number; start: number; end: number; words: W[]};\nexport const VOC: Record<string, Line> = '+json.dumps({k:dict(who=v['who'],at=v['at'],start=v['start'],end=v['end'],words=v['words']) for k,v in out.items()})+';\nexport const TOTAL_S = '+str(TOTAL)+';\n')
