# Gary Agents · Version C2 VO assembly: picks -> trimmed, processed line wavs (here) + cues.json + src/voC2.ts.
# Same chain + word-time method as audio/vo_c/build_vo.py (Version C untouched). Reused C takes are read from ../vo_c/takes.
import json,subprocess,re,numpy as np
from span import span
C='../vo_c/takes/'
# (line, take path, gap after previous speech end, optional max source time (s) to cut a take short)
PICKS=[('n01',C+'n01_s51',0.25,None),('n02',C+'n02_s23',0.30,None),('n03',C+'n03_s51',0.28,None),
('d1p',C+'d1p_s11',0.32,None),('d1r',C+'d1r_s11',0.50,None),('d1p2',C+'d1p2_s11',0.28,None),
('n05',C+'n05_s23',1.25,None),
('n06','takes/n06_s37',0.40,None),('n07','takes/n07_s11',0.30,None),('n08','takes/n08_s37',0.30,None),('n09',C+'n09_s37',0.30,None),
('n11','takes/n11_s11',0.30,None),        # SLEEP SHOT opens: "Brief them once. Then close your eyes." -> "eyes." onset = K1 (sleep-shot local 0.0)
('n10',C+'n10_s37','K2',1.95),            # C take cut after "...in the background." -- now plays over K2 (Mark expands), EYES+K2_VO
('n12','takes/n12_s23','HARD',None),      # HARD cut to the 7:12 lock at EYES+SLEEP_LEN (top of the stretch); "By morning" HARD+0.27
('n13','takes/n13_s11',1.05,None),        # honest-flag hold (half a beat longer than comfortable)
('d2p',C+'d2p_s37',0.45,None),('d2r',C+'d2r_s23',0.22,None),('d2p2','takes/d2p2_s11',0.38,None),
('n15','takes/n15_s23',0.55,None)]
END_HOLD=0.9
SLEEP_LEN=14.9; K2_VO=1.37; HARD_LEAD=0.27   # C2 sleep stretch (opus/C2-SLEEP-STRETCH-EDIT.md): K1..K6 = EYES+0.0/1.1/4.6/9.1/13.1/14.1, hard cut EYES+14.9
KEYS=[0,1.1,4.6,9.1,13.1,14.1]
HITS={'mark':62,'gary':88,'fiona':76,'thunk':58}   # local frames after K2/K3/K4/K3 (shared by GaryC2.tsx + mix_c2.py)
EYES=None
NAR="highpass=f=75:poles=2,lowshelf=f=180:g=2:w=0.7,equalizer=f=350:t=q:w=1.2:g=-1.5,acompressor=threshold=-22dB:ratio=3:attack=12:release=80:makeup=2"
DIA="highpass=f=160:poles=2,lowpass=f=7500,equalizer=f=2500:t=q:w=1.0:g=2,acompressor=threshold=-22dB:ratio=3:attack=10:release=80:makeup=2"
out={}; prev_end=0.0
for n,src,gap,cut in PICKS:
    f=src+'.mp3'; a,b,dur=span(f)
    if cut:
        # recompute speech end inside [0,cut]
        x=np.frombuffer(subprocess.run(['ffmpeg','-v','error','-i',f,'-t',str(cut),'-ar','16000','-ac','1','-f','f32le','-'],capture_output=True).stdout,np.float32)
        h=160;k=len(x)//h;e=20*np.log10(np.sqrt((x[:k*h].reshape(k,h)**2).mean(1))+1e-9);s=np.where(e>e.max()-40)[0]; b=(s[-1]+1)/100; dur=cut
    a0=max(0,a-0.02); b0=min(dur,b+0.12)
    who='N' if n[0]=='n' else ('P' if n.endswith('p') or n.endswith('p2') else 'R')
    subprocess.run(['ffmpeg','-y','-v','error','-ss',f'{a0:.3f}','-to',f'{b0:.3f}','-i',f,'-af',(NAR if who=='N' else DIA)+f',afade=t=in:d=0.005,afade=t=out:st={b0-a0-0.04:.3f}:d=0.04','-ar','48000','-ac','1','-c:a','pcm_s24le',f'{n}.wav'],check=True)
    if gap=='K2': at=round(EYES+K2_VO-(a-a0),3)
    elif gap=='HARD': at=round(EYES+SLEEP_LEN+HARD_LEAD-(a-a0),3)
    else: at=round(gap-(a-a0),3) if n=='n01' else round(prev_end+gap-(a-a0),3)
    j=json.load(open(src+'.json'))['alignment']; ch=j['characters']; st=j['character_start_times_seconds']; en=j['character_end_times_seconds']
    words=[]; cur=''; ws=we=None
    for c,s,e in zip(ch,st,en):
        if c.isspace():
            if cur: words.append([cur,ws,we]); cur=''
        else:
            if not cur: ws=s
            cur+=c; we=e
    if cur: words.append([cur,ws,we])
    words=[w for w in words if not re.match(r'^(<break|time=|/>)',w[0])]
    if cut: words=[w for w in words if w[1]<cut-0.05]
    if n=='n01': words=[['11:41',words[0][1],words[1][2]],['PM.',words[2][1],words[2][2]]]+words[3:]
    words=[[w[0].replace('Delhi–Abu','DEL–AUH').replace('...','…'),w[1],w[2]] for w in words if w[0] not in ('Dhabi?','Dhabi.')]
    words=[[('DEL–AUH?' if w[0]=='DEL–AUH' and n=='d1p' else 'DEL–AUH.' if w[0]=='DEL–AUH' else w[0]),w[1],w[2]] for w in words]
    W=[[w[0],round(at+max(0,w[1]-a0),3),round(at+max(0.05,w[2]-a0),3)] for w in words]
    out[n]=dict(who=who,src=src,at=at,dur=round(b0-a0,3),start=round(at+(a-a0),3),end=round(at+(b-a0),3),words=W)
    prev_end=at+(b-a0)
    if n=='n11': EYES=W[-1][1]
for n,v in out.items():
    ws=v['words']
    for i,w in enumerate(ws):
        if w[0].startswith('DEL–AUH'): w[2]=round(ws[i+1][1]-0.05,3) if i+1<len(ws) else v['end']
TOTAL=round(prev_end+END_HOLD,3)
json.dump(dict(lines=out,total=TOTAL,sleep=dict(eyes=EYES,len=SLEEP_LEN,keys=KEYS,hits=HITS)),open('cues.json','w'),indent=1)
for n,v in out.items(): print(f"{n:5s} {v['who']} {v['start']:6.2f}-{v['end']:6.2f}  {' '.join(w[0] for w in v['words'])}")
print('TOTAL',TOTAL,'frames',round(TOTAL*30))
open('../../src/voC2.ts','w').write('// GENERATED by audio/vo_c2/build_vo_c2.py (ElevenLabs alignment word times, seconds on the Gary Agents Version C2 timeline).\nexport type W = [string, number, number];\nexport type Line = {who: "N" | "P" | "R"; at: number; start: number; end: number; words: W[]};\nexport const VOC2: Record<string, Line> = '+json.dumps({k:dict(who=v['who'],at=v['at'],start=v['start'],end=v['end'],words=v['words']) for k,v in out.items()})+';\nexport const TOTAL_S = '+str(TOTAL)+';\nexport const SLEEP = '+json.dumps(dict(eyes=EYES,len=SLEEP_LEN,keys=KEYS,hits=HITS))+';\n')
